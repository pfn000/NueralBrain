//! The main runtime handle for interacting with a brain.

use crate::builder::BrainConfig;
use crate::error::{SdkError, SdkResult};
use crate::input::InputBatch;
use crate::output::BrainOutput;
use crate::persistence::{SaveFormat, StateBundle};
use bionetic_core::ids::DotId;
use bionetic_core::pulse::Pulse;
use bionetic_engine::engine::BioneticEngine;

/// The main runtime handle for a brain.
pub struct BrainHandle {
    engine: BioneticEngine,
    config: BrainConfig,
    current_tick: u64,
}

impl BrainHandle {
    /// Construct from an engine and configuration.
    pub(crate) fn from_parts(engine: BioneticEngine, config: BrainConfig) -> Self {
        let current_tick = engine.tick;
        Self { engine, config, current_tick }
    }

    /// Inject values into the sensory corpus and advance one tick.
    pub fn think(&mut self, input: &[f32]) -> Vec<f32> { self.think_detailed(input).motor }

    /// Think and return diagnostics.
    pub fn think_detailed(&mut self, input: &[f32]) -> BrainOutput {
        self.try_think(input).expect("think() failed")
    }

    /// Non-panicking variant of think_detailed.
    pub fn try_think(&mut self, input: &[f32]) -> SdkResult<BrainOutput> {
        if input.len() > self.config.max_input_pulses {
            return Err(SdkError::InvalidInput(format!(
                "input size {} exceeds max_input_pulses {}",
                input.len(), self.config.max_input_pulses
            )));
        }
        let tick = self.current_tick.saturating_add(1);
        for (index, &value) in input.iter().enumerate() {
            let pulse = Pulse::value_pulse(DotId(index as u64), value as f64, value.abs() as f64, tick);
            let _ = self.engine.inject_multimodal_pulse(pulse);
        }
        self.engine.tick();
        self.current_tick = self.engine.tick;
        Ok(self.snapshot())
    }

    /// Inject a typed batch into a selected corpus and advance one tick.
    pub fn think_batch(&mut self, batch: InputBatch) -> BrainOutput {
        self.try_think_batch(batch).expect("think_batch() failed")
    }

    /// Non-panicking batch processing.
    pub fn try_think_batch(&mut self, batch: InputBatch) -> SdkResult<BrainOutput> {
        if batch.total_pulses() > self.config.max_input_pulses {
            return Err(SdkError::InvalidInput(format!(
                "batch size {} exceeds max_input_pulses {}",
                batch.total_pulses(), self.config.max_input_pulses
            )));
        }
        let target = batch.target_corpus;
        if !self.engine.has_corpus(target) {
            return Err(SdkError::InvalidInput(format!("corpus {} is not present in this brain", target.0)));
        }
        let tick = self.current_tick.saturating_add(1);
        for pulse in batch.into_pulses(tick) {
            let _ = self.engine.inject_pulse_object(target, pulse);
        }
        self.engine.tick();
        self.current_tick = self.engine.tick;
        Ok(self.snapshot())
    }

    /// Think, then apply a reward signal.
    pub fn learn(&mut self, input: &[f32], reward: f32) -> BrainOutput {
        let output = self.think_detailed(input);
        self.engine.apply_reward(reward.clamp(-1.0, 1.0));
        output
    }

    /// Enter dream state and run consolidation ticks.
    pub fn dream(&mut self, ticks: usize) -> usize {
        if !self.config.enable_dreaming { return 0; }
        self.engine.enter_dream();
        for _ in 0..ticks { self.engine.tick(); }
        self.engine.wake();
        self.current_tick = self.engine.tick;
        ticks
    }

    /// Advance the engine without new input.
    pub fn idle(&mut self, ticks: usize) {
        for _ in 0..ticks { self.engine.tick(); }
        self.current_tick = self.engine.tick;
    }

    /// Inject pulses generated by a vision or other multimodal pipeline.
    pub fn inject_multimodal_pulses(&mut self, pulses: Vec<Pulse>) -> SdkResult<BrainOutput> {
        if pulses.len() > self.config.max_input_pulses {
            return Err(SdkError::InvalidInput(format!(
                "pulse count {} exceeds max_input_pulses {}",
                pulses.len(), self.config.max_input_pulses
            )));
        }
        for pulse in pulses { let _ = self.engine.inject_multimodal_pulse(pulse); }
        self.engine.tick();
        self.current_tick = self.engine.tick;
        Ok(self.snapshot())
    }

    /// Inject a multimodal input container and advance one tick.
    #[cfg(feature = "multimodal")]
    pub fn think_multimodal(&mut self, input: bionetic_core::multimodal::MultiModalInput) -> BrainOutput {
        let _ = self.engine.inject_multimodal_input(input);
        self.engine.tick();
        self.current_tick = self.engine.tick;
        self.snapshot()
    }

    fn snapshot(&self) -> BrainOutput {
        BrainOutput {
            motor: self.engine.read_motor_output(),
            tick: self.current_tick,
            chemicals: self.engine.chemical_snapshot(),
            active_dots: self.engine.active_dot_count(),
            propagated_pulses: self.engine.propagated_pulse_count(),
        }
    }

    /// Current simulation tick.
    pub fn tick(&self) -> u64 { self.current_tick }
    /// Total dots across all corpora.
    pub fn dot_count(&self) -> usize { self.engine.total_dots() }
    /// Current average chemical levels.
    pub fn chemicals(&self) -> bionetic_core::chemicals::ChemicalSnapshot { self.engine.chemical_snapshot() }
    /// Current builder configuration.
    pub fn config(&self) -> &BrainConfig { &self.config }
    /// Read-only engine access.
    pub fn engine(&self) -> &BioneticEngine { &self.engine }
    /// Mutable engine access.
    pub fn engine_mut(&mut self) -> &mut BioneticEngine { &mut self.engine }

    /// Serialize the brain and engine state.
    pub fn save(&self) -> Vec<u8> { self.save_as(SaveFormat::default()).expect("save() failed") }

    /// Save with a selected encoding.
    pub fn save_as(&self, format: SaveFormat) -> SdkResult<Vec<u8>> {
        let engine_bytes = self.engine.serialize_state().map_err(SdkError::Persistence)?;
        let engine_state = serde_json::from_slice(&engine_bytes)?;
        StateBundle {
            version: StateBundle::CURRENT_VERSION,
            config: self.config.clone(),
            engine_state,
            saved_at_tick: self.current_tick,
        }.to_bytes(format)
    }

    /// Restore engine and SDK state from a serialized bundle.
    pub fn load(&mut self, bytes: &[u8]) -> SdkResult<()> {
        let bundle = StateBundle::from_bytes(bytes)?;
        let engine_bytes = serde_json::to_vec(&bundle.engine_state)?;
        self.engine.deserialize_state(&engine_bytes).map_err(SdkError::Persistence)?;
        self.current_tick = bundle.saved_at_tick;
        self.config = bundle.config;
        Ok(())
    }

    /// Reset neurochemistry while preserving learned structure and the current tick.
    pub fn soft_reset(&mut self) {
        self.engine.reset_chemicals();
        self.current_tick = self.engine.tick;
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use bionetic_core::ids::CorpusId;
    use crate::builder::BrainBuilder;

    #[test]
    fn test_basic_think() {
        let mut brain = BrainBuilder::new().with_corpora(4).with_dots_per_corpus(32).build();
        let output = brain.think(&[0.5, 0.3, 0.8]);
        assert_eq!(brain.tick(), 1);
        assert!(output.is_empty());
    }

    #[test]
    fn test_think_detailed() {
        let mut brain = BrainBuilder::new().with_corpora(8).with_dots_per_corpus(16).build();
        let result = brain.think_detailed(&[0.5]);
        assert_eq!(result.tick, 1);
        assert_eq!(result.motor.len(), 16);
    }

    #[test]
    fn test_learn() {
        let mut brain = BrainBuilder::new().build();
        let result = brain.learn(&[0.5, 0.5], 0.9);
        assert_eq!(result.tick, 1);
        assert!(brain.chemicals().dopamine.is_finite());
    }

    #[test]
    fn test_dream_respects_config() {
        let mut brain = BrainBuilder::new().with_dreaming(false).build();
        assert_eq!(brain.dream(100), 0);
        let mut brain = BrainBuilder::new().with_dreaming(true).build();
        assert_eq!(brain.dream(5), 5);
    }

    #[test]
    fn test_idle_advances_tick() {
        let mut brain = BrainBuilder::new().build();
        brain.idle(10);
        assert_eq!(brain.tick(), 10);
    }

    #[test]
    fn test_input_overflow_rejected() {
        let mut brain = BrainBuilder::new().with_max_input_pulses(5).build();
        assert!(matches!(brain.try_think(&vec![0.5; 100]), Err(SdkError::InvalidInput(_))));
    }

    #[test]
    fn test_input_batch() {
        let mut brain = BrainBuilder::new().build();
        let batch = InputBatch::new(CorpusId(1)).with_values(&[0.5, 0.3]).with_rewards(&[0.8]);
        assert_eq!(brain.think_batch(batch).tick, 1);
    }

    #[test]
    fn test_save_load_roundtrip() {
        let mut brain = BrainBuilder::new().with_corpora(8).with_dots_per_corpus(16).build();
        brain.idle(5);
        let bytes = brain.save();
        let mut restored = BrainBuilder::new().build();
        restored.load(&bytes).expect("load should succeed");
        assert_eq!(restored.tick(), 5);
        assert_eq!(restored.dot_count(), brain.dot_count());
    }

    #[test]
    fn test_soft_reset_keeps_tick() {
        let mut brain = BrainBuilder::new().build();
        brain.idle(4);
        brain.soft_reset();
        assert_eq!(brain.tick(), 4);
    }
}
